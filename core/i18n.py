def language_options(language_codes: tuple[str, ...] | None = None) -> dict[str, str]:
    if language_codes is None:
        return dict(LANGUAGE_OPTIONS)
    allowed = set(language_codes)
    return {label: code for label, code in LANGUAGE_OPTIONS.items() if code in allowed}


def translate(key: str, language: str = DEFAULT_LANGUAGE, **values) -> str:
    selected = language if language in TRANSLATIONS else DEFAULT_LANGUAGE
    template = TRANSLATIONS[selected].get(key, TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key))
    return template.format(**values) if values else template


def missing_translation_keys() -> dict[str, set[str]]:
    all_keys = set().union(*(translations.keys() for translations in TRANSLATIONS.values()))
    return {
        language: all_keys - set(translations)
        for language, translations in TRANSLATIONS.items()
        if all_keys - set(translations)
    }
